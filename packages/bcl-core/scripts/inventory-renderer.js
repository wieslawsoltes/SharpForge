import {compareMembers} from '../../../scripts/conformance/inventory/bcl-api-diff.js';

export const inventoryStart = '<!-- bcl-module-inventory:start -->';
export const inventoryEnd = '<!-- bcl-module-inventory:end -->';

function code(value) {
  return '<code>' + String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;').replaceAll('|', '&#124;') + '</code>';
}

function signature(member) {
  const prefix = member.isStatic ? 'static ' : '';
  return `${prefix}${member.result} ${member.owner}::${member.name}(${member.parameters.join(', ')})`;
}

function moduleSections(modules, contracts, types) {
  const families = new Map();
  const names = new Set();
  const sections = modules.map(module => {
    if (names.has(module.name)) throw new Error('Duplicate inventory module: ' + module.name);
    names.add(module.name);
    const section = {module, members: [], references: []};
    for (const family of module.families) {
      if (families.has(family)) throw new Error('Duplicate inventory family: ' + family);
      families.set(family, section);
    }
    return section;
  });
  for (const contract of contracts) {
    const family = types.get(contract.owner)?.family;
    families.get(family)?.members.push(contract);
  }
  for (const section of sections) section.members.sort((left, right) => left.id - right.id);
  return {sections, families};
}

function renderModule(section) {
  const {module, members, references} = section;
  const lines = [`### Module ${code(module.name)}`, '', `Registered families: ${module.families.map(code).join(', ')}.`, ''];
  lines.push('| ABI ID | Registered signature | Registry status |', '| --- | --- | --- |');
  for (const member of members) lines.push(`| ${member.id} | ${code(signature(member))} | implemented |`);
  if (!members.length) lines.push('| — | No registered members | — |');
  lines.push('');
  if (!references.length) {
    lines.push('No pinned reference inventory is included for these families; registered rows alone do not establish API coverage.', '');
    return lines;
  }
  const implemented = references.filter(row => row.status === 'implemented').length;
  lines.push(`Pinned reference: ${implemented} implemented and ${references.length - implemented} missing exact metadata rows.`, '');
  lines.push('| Reference kind | Exact reference signature | Status | Matching ABI IDs |', '| --- | --- | --- | --- |');
  for (const row of references) {
    lines.push(`| ${row.kind} | ${code(row.signature)} | ${row.status} | ${row.contractIds.join(', ') || '—'} |`);
  }
  lines.push('');
  return lines;
}

/** Render registered module members and exact pinned metadata presence, without implying runtime parity. */
export function renderInventory({modules, contracts, types, reference}) {
  const {sections, families} = moduleSections(modules, contracts, types);
  const comparison = compareMembers(reference, {registryTypes: types, registryContracts: contracts, area: 'A07'});
  const unassigned = [];
  for (const row of comparison.rows) {
    const family = types.get(row.owner)?.family;
    const section = families.get(family);
    if (section) section.references.push(row);
    else unassigned.push(row.owner);
  }
  if (unassigned.length) throw new Error('Reference types have no registered BCL module: ' + [...new Set(unassigned)].join(', '));
  const lines = [
    inventoryStart,
    '## Registered BCL modules and pinned reference status',
    '',
    'Generated by `node packages/bcl-core/scripts/inventory.js`. The released contract lists above remain available for existing links.',
    '',
    `Reference: .NET ${reference.runtime}, reference pack ${reference.referencePack}, SDK ${reference.extractor.sdk}.`,
    'The snapshot contains public metadata for String, StringBuilder, Array and Random; inherited members are not expanded.',
    '“Implemented” means an exact registered signature exists. It does not establish behavioral parity on any execution engine.',
    'Closed Array overloads do not satisfy open generic reference signatures. Fields and properties remain distinct metadata kinds.',
    '',
    'Reference source and extractor hashes are retained in [the pinned snapshot](../packages/bcl-core/reference/dotnet-10.0.5.json).',
    'Use `node packages/bcl-core/scripts/inventory.js --check` to reject stale or missing registered-member documentation.',
    ''
  ];
  for (const section of sections) lines.push(...renderModule(section));
  lines.push(inventoryEnd, '');
  return lines.join('\n');
}

/** Replace only the generated suffix, retaining all existing released contract sections byte-for-byte. */
export function updateInventoryDocument(document, options) {
  const start = document.indexOf(inventoryStart);
  if (start >= 0 && document.indexOf(inventoryEnd, start) < 0) throw new Error('Unterminated BCL module inventory');
  const prefix = start < 0 ? document : document.slice(0, start);
  const separator = prefix.endsWith('\n\n') ? '' : prefix.endsWith('\n') ? '\n' : '\n\n';
  return prefix + separator + renderInventory(options);
}

/** Fail documentation checks if any module row is missing, extra, changed, or in a noncanonical order. */
export function assertInventoryDocument(document, options) {
  if (!document.includes(inventoryStart) || document !== updateInventoryDocument(document, options)) {
    throw new Error('BCL module inventory is stale; run node packages/bcl-core/scripts/inventory.js');
  }
}

/** Redirect released Array/Random documentation to the module inventory without changing neighboring sections. */
export function updateRuntimeDocument(document) {
  let result = document;
  for (const owner of ['System.Array', 'System.Random']) {
    const heading = '## ' + owner + '\n';
    const start = result.indexOf(heading);
    if (start < 0) throw new Error('Runtime inventory is missing ' + owner);
    const next = result.indexOf('\n## ', start + heading.length);
    const end = next < 0 ? result.length : next + 1;
    const pointer = heading + '\nRegistered contracts and pinned reference status are maintained in '
      + '[the BCL module inventory](bcl-api.md#registered-bcl-modules-and-pinned-reference-status).\n\n';
    result = result.slice(0, start) + pointer + result.slice(end);
  }
  return result;
}
