import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

/** Compress consecutive mappings with the same delta and stride; unmapped code points stay unchanged. */
export function casingRanges(mappings) {
  const ranges = [];
  for (let index = 0; index < mappings.length;) {
    const [start, mapped] = mappings[index++];
    const delta = mapped - start;
    let end = start;
    let stride = 1;
    const next = mappings[index];
    if (next && next[1] - next[0] === delta && next[0] - start <= 2) stride = next[0] - start;
    while (index < mappings.length && mappings[index][0] - end === stride &&
        mappings[index][1] - mappings[index][0] === delta) end = mappings[index++][0];
    ranges.push([start, end, delta, stride]);
  }
  return ranges;
}

export function renderCasingTable(mappings, direction, sourceHash) {
  const rows = casingRanges(mappings).map(([start, end, delta, stride]) =>
    `  0x${start.toString(16)}, 0x${end.toString(16)}, ${delta}, ${stride},`);
  return [
    '// Generated by scripts/generate-unicode-casing.js from the pinned .NET 10.0.5 scalar oracle.',
    '// Capture source SHA-256: ' + sourceHash,
    '// Each row is [first code point, last code point, mapping delta, input stride].',
    `export const ${direction}CaseRanges = Object.freeze([`,
    ...rows,
    ']);',
    ''
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const reference = JSON.parse(readFileSync(new URL('../reference/unicode-dotnet-10.0.5.json', import.meta.url), 'utf8'));
  for (const direction of ['upper', 'lower']) {
    const target = new URL(`../src/system/unicode-${direction}-case.js`, import.meta.url);
    writeFileSync(target, renderCasingTable(reference[direction], direction, reference.extractor.sourceSHA256));
  }
}
