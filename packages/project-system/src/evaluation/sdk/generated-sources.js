import { getCaseInsensitive, toBoolean } from '../errors.js';

const predefinedTypes = new Set(['bool', 'byte', 'char', 'decimal', 'double', 'dynamic', 'float', 'int', 'long',
  'nint', 'nuint', 'object', 'sbyte', 'short', 'string', 'uint', 'ulong', 'ushort']);

function stringLiteral(value) {
  return JSON.stringify(String(value)).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function globalUsings(context) {
  const items = getCaseInsensitive(context.items, 'Using') ?? [];
  const statements = [];
  const seen = new Set();
  for (const item of items) {
    const alias = getCaseInsensitive(item.metadata, 'Alias');
    const isStatic = toBoolean(getCaseInsensitive(item.metadata, 'Static'));
    if (!/^(?:global::)?[A-Za-z_][\w.]*(?:<[^;{}]+>)?$/.test(item.identity) || alias && !/^@?[A-Za-z_]\w*$/.test(alias)) {
      context.diagnostic(`Invalid Using item '${item.identity}'.`, null, 'SFP1401');
      continue;
    }
    const qualified = item.identity.startsWith('global::') || predefinedTypes.has(item.identity) ? item.identity : 'global::' + item.identity;
    const statement = 'global using ' + (isStatic ? 'static ' : '') + (alias ? alias + ' = ' : '') + qualified + ';';
    if (!seen.has(statement)) statements.push(statement);
    seen.add(statement);
  }
  if (!statements.length) return null;
  return '// <auto-generated/>\n' + statements.join('\n') + '\n';
}

function assemblyInfo(context) {
  const properties = context.properties;
  if (!properties.targetframework || !toBoolean(properties.generateassemblyinfo, true)) return null;
  const attributes = [];
  const mapping = {
    Company: 'AssemblyCompany', Configuration: 'AssemblyConfiguration', Copyright: 'AssemblyCopyright',
    Description: 'AssemblyDescription', FileVersion: 'AssemblyFileVersion', InformationalVersion: 'AssemblyInformationalVersion',
    Product: 'AssemblyProduct', AssemblyTitle: 'AssemblyTitle', AssemblyVersion: 'AssemblyVersion', NeutralLanguage: 'NeutralResourcesLanguage',
  };
  for (const [property, attribute] of Object.entries(mapping)) {
    const value = properties[property.toLowerCase()];
    if (!value || !toBoolean(properties['generate' + attribute.toLowerCase() + 'attribute'], true)) continue;
    const namespace = attribute === 'NeutralResourcesLanguage' ? 'System.Resources' : 'System.Reflection';
    attributes.push({ type: `${namespace}.${attribute}Attribute`, value });
  }
  for (const item of getCaseInsensitive(context.items, 'InternalsVisibleTo') ?? []) {
    const publicKey = getCaseInsensitive(item.metadata, 'Key') ?? getCaseInsensitive(item.metadata, 'PublicKey');
    const identity = item.identity + (publicKey ? ', PublicKey=' + publicKey : '');
    attributes.push({ type: 'System.Runtime.CompilerServices.InternalsVisibleToAttribute', value: identity });
  }
  return attributes.length ? {
    text: '// <auto-generated/>\n' + attributes.map(attribute => `[assembly: ${attribute.type}(${stringLiteral(attribute.value)})]`).join('\n') + '\n',
    attributes,
  } : null;
}

/** Generate deterministic virtual sources, without modifying caller-provided workspace records. */
export function generateSdkSources(context) {
  const root = context.properties.intermediateoutputpath ?? 'obj/';
  const name = context.properties.msbuildprojectname;
  const assembly = assemblyInfo(context);
  const sources = [
    [name + '.GlobalUsings.g.cs', globalUsings(context), 'global-usings', []],
    [name + '.AssemblyInfo.g.cs', assembly?.text, 'assembly-info', assembly?.attributes ?? []],
  ];
  context.generatedSources = sources.filter(([, text]) => text).map(([file, text, kind, assemblyAttributes]) => ({
    path: context.resolvePath(root + file), text, kind, generated: true, assemblyAttributes,
  }));
  return context.generatedSources;
}
