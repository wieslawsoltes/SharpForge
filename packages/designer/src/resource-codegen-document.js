import {CONTROLS, XAML} from '@sharpforge/framework';
import {childSlot, propertySchema, resolvedProperties, validateDesign} from './model.js';
import {authoringError, resourceKey} from './property-diagnostics.js';
import {attachedDesignerAssignment, designCodegenDiagnostics, generateDesignerNodeStatements} from './resource-codegen.js';
import {generateDesignerStyles, generateDesignerTemplateFactory} from './resource-codegen-templates.js';
import {csharpValue, designerSymbol, quoteDesignerString} from './resource-codegen-values.js';
import {generateWinuiXamlCode} from './resource-xaml.js';
import {generateResponsiveMethods} from './layout-authoring-responsive.js';

function emitProperties(design, node, variable) {
  const lines = [];
  const effective = resolvedProperties(design, node);
  const captured = Object.fromEntries(Object.entries(node.baseProperties ?? {})
    .filter(([property]) => effective.sources[property] === 'runtime style/default'));
  for (const [property, value] of Object.entries({...captured, ...node.properties})) {
    const definition = propertySchema(node.type)[property];
    if (!definition || definition.readOnly || definition.isStatic) continue;
    lines.push(attachedDesignerAssignment(node.type, property, variable, csharpValue(value, definition.type)));
  }
  return lines;
}

function emitTracks(node, variable) {
  const lines = [];
  const axes = [['rows', 'RowDefinitions', 'Height', 'RowDefinition'], ['columns', 'ColumnDefinitions', 'Width', 'ColumnDefinition']];
  for (const [key, property, member, type] of axes) {
    for (const length of node[key] ?? []) {
      lines.push(`${variable}.${property}.Add(new ${CONTROLS}${type}() { ${member} = ${csharpValue(length, XAML + 'GridLength')} });`);
    }
  }
  return lines;
}

function needsWinuiMarkup(design) {
  return Object.keys(design.resources ?? {}).length > 0 || Object.keys(design.templates).length > 0 ||
    design.nodes.some(node => Object.keys(node.bindings ?? {}).length || Object.keys(node.resourceReferences ?? {}).length || node.states?.length ||
      ['Image', 'CalendarDatePicker', 'TimePicker'].some(type => node.type === CONTROLS + type));
}

/** Deterministic generation preserves the released SharpForge profile and reports unsupported runtime features. */
export function generateDesignCode(input, {className = 'DesignedView', activate = true, target = 'sharpforge'} = {}) {
  const design = validateDesign(input);
  resourceKey(className);
  const diagnostics = designCodegenDiagnostics(design, {target});
  if (diagnostics.some(item => item.severity === 'error')) {
    const error = new Error(diagnostics.map(item => item.message).join('\n'));
    error.code = 'SFD1872';
    error.diagnostics = diagnostics;
    throw error;
  }
  const symbols = design.nodes.map(node => designerSymbol(node.id));
  if (new Set(symbols).size !== symbols.length) authoringError('SFD1873', 'Node IDs collide after C# identifier conversion.');
  const responsive = generateResponsiveMethods(design, {symbol: designerSymbol, csharpValue});
  if (target === 'winui' && needsWinuiMarkup(design)) return generateWinuiXamlCode(design, {className, activate, responsive});
  const lines = ['// Generated by SharpForge Designer. Edit the design document or link this C# file with Connect C#.',
    `public class ${className}`, '{'];
  const body = generateDesignerStyles(design, {target});
  const templates = [];
  for (const node of design.nodes) lines.push(`    public static ${node.projectType ?? node.type} ${designerSymbol(node.id)};`);
  for (const [key, template] of Object.entries(design.templates)) {
    templates.push(...generateDesignerTemplateFactory(key, template));
    body.push(`${CONTROLS}ControlTemplate template_${key} = Template_${key}();`);
  }
  for (const node of design.nodes) {
    const variable = designerSymbol(node.id);
    body.push(`${variable} = new ${node.projectType ?? node.type}();`, ...emitProperties(design, node, variable));
    if (node.style) body.push(`${variable}.Style = style_${node.style};`);
    else {
      for (const [key, style] of Object.entries(design.styles)) {
        if (style.implicit && style.targetType === node.type) body.push(`${variable}.Style = style_${key};`);
      }
    }
    if (node.template) body.push(`${variable}.Template = template_${node.template};`);
    for (const [event, handler] of Object.entries(node.events)) body.push(`${variable}.${event} += ${handler};`);
    body.push(...emitTracks(node, variable), ...generateDesignerNodeStatements(design, node, variable, {target}));
  }
  for (const node of [...design.nodes].reverse()) {
    const slot = childSlot(node.type);
    for (const child of node.children) {
      body.push(`${designerSymbol(node.id)}.${slot.property}${slot.many ? `.Add(${designerSymbol(child)})` : ` = ${designerSymbol(child)}`};`);
    }
  }
  let root = designerSymbol(design.root);
  if (design.nodes.find(node => node.id === design.root).type !== XAML + 'Window') {
    body.push(`${XAML}Window window = new ${XAML}Window() { Content = ${root}, Title = ${quoteDesignerString(design.name)} };`);
    root = 'window';
  }
  body.push(...responsive.initialize);
  if (activate) body.push(`${root}.Activate();`);
  body.push(`return ${root};`);
  lines.push(`    public static ${XAML}Window Create()`, '    {', ...body.map(line => '        ' + line),
    '    }', ...templates, ...responsive.methods, '}');
  return lines.join('\n') + '\n';
}

export function generateDesignProject(input, options = {}) {
  const design = validateDesign(input);
  const handlers = [...new Set(design.nodes.flatMap(node => Object.values(node.events))
    .filter(name => name.startsWith('Program.')).map(name => name.slice(8)))];
  const handlerText = handlers.map(name => `    public static void ${name}(object sender, RoutedEventArgs args)\n` +
    `    {\n        Console.WriteLine(${quoteDesignerString(name + ' invoked')});\n    }`).join('\n');
  const project = '<Project Sdk="Microsoft.NET.Sdk">\n  <PropertyGroup><OutputType>Exe</OutputType>' +
    '<TargetFramework>net10.0</TargetFramework><SharpForgeProfile>WinUIWeb</SharpForgeProfile></PropertyGroup>\n</Project>\n';
  if (options.target === 'winui') {
    authoringError('SFD1875', 'WinUI source export is supported. Project generation requires a platform-specific WinUI host project.');
  }
  return [
    {path: 'View.sfdesign.json', text: JSON.stringify(design, null, 2) + '\n'},
    {path: 'DesignedView.g.cs', text: generateDesignCode(design, options)},
    {path: 'Program.cs', text: `using Microsoft.UI.Xaml;\nclass Program\n{\n` +
      `    static void Main() { DesignedView.Create(); }\n${handlerText}\n}\n`},
    {path: 'DesignerApp.csproj', text: project},
    {path: 'DesignerApp.slnx', text: '<Solution>\n  <Project Path="DesignerApp.csproj" />\n</Solution>\n'}
  ];
}
