/** A complete template contribution in one module, installed into a caller-owned catalog. */
export default Object.freeze({
  id: 'example-notice', kind: 'item', name: 'Notice', category: 'Configuration', language: 'Text',
  description: 'A text notice registered without editing the built-in catalog.', fileName: 'NOTICE.txt',
  targets: ['data'],
  generate(_template, { folder, name }) {
    return { records: [{ path: [folder, name].filter(Boolean).join('/'), text: 'Generated by a catalog contribution.\n' }] };
  }
});
