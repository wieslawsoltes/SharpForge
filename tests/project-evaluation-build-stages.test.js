import test from 'node:test';
import assert from 'node:assert/strict';
import {ProjectSystem, getCaseInsensitive} from '@sharpforge/project-system';

const sdk = (properties = '', targets = '') => '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup>'
  + '<TargetFramework>net10.0</TargetFramework><GenerateAssemblyInfo>false</GenerateAssemblyInfo>'
  + properties + '</PropertyGroup>' + targets + '</Project>';

function system(xml, extra = []) {
  const value = new ProjectSystem([{path: 'App/App.csproj', text: xml}, ...extra]);
  value.load('App/App.csproj');
  return value;
}

test('SDK target stages run every before hook and pause before after hooks until actual output bytes arrive', () => {
  const value = system(sdk('',
    '<Target Name="First" BeforeTargets="BeforeBuild"><WriteLinesToFile File="first.txt" Lines="first"/></Target>'
    + '<Target Name="Second" BeforeTargets="BeforeBuild"><WriteLinesToFile File="second.txt" Lines="second"/></Target>'
    + '<Target Name="After" AfterTargets="CoreCompile"><Copy SourceFiles="$(TargetPath)" DestinationFiles="copied.dll"/></Target>'
    + '<Target Name="Finish" AfterTargets="Build"><WriteLinesToFile File="finish.txt" Lines="done"/></Target>'));
  const prepared = value.runTargets('App/App.csproj', undefined, {phase: 'beforeCompile'});
  assert.equal(prepared.success, true, JSON.stringify(prepared.diagnostics));
  assert.equal(prepared.awaitingCompilation, true);
  assert(prepared.executed.indexOf('First') < prepared.executed.indexOf('Second'));
  assert.equal(value.files.has('App/first.txt'), true);
  assert.equal(value.files.has('App/second.txt'), true);
  assert.equal(value.files.has('App/copied.dll'), false);
  assert.equal(value.files.has('App/finish.txt'), false);
  const output = value.buildPlan().units[0].output;
  const failed = value.runTargets('App/App.csproj', undefined, {phase: 'afterCompile', outputs: []});
  assert.equal(failed.success, false);
  assert.equal(value.files.has(output.slice(1)), false);
  const bytes = Uint8Array.of(77, 90, 1, 2);
  const complete = value.runTargets('App/App.csproj', undefined,
    {phase: 'afterCompile', outputPath: output, outputs: [{path: output, bytes}]});
  assert.equal(complete.success, true, JSON.stringify(complete.diagnostics));
  assert.equal(complete.awaitingCompilation, false);
  assert.deepEqual(value.files.get('App/copied.dll').bytes, bytes);
  assert.equal(value.files.get('App/finish.txt').text, 'done\n');
  assert(complete.executed.indexOf('CoreCompile') < complete.executed.indexOf('After'));
  assert(complete.executed.indexOf('After') < complete.executed.indexOf('Finish'));
  assert.throws(() => value.runTargets('App/App.csproj', undefined, {phase: 'afterCompile'}), /prepared context/);
});

test('framework contexts retain distinct target-generated bytes at the same path and rebuild from initial items', () => {
  const xml = sdk('<TargetFrameworks>net8.0;net10.0</TargetFrameworks><EnableDefaultCompileItems>false</EnableDefaultCompileItems>',
    '<Target Name="Generate" BeforeTargets="BeforeCompile">'
    + '<WriteLinesToFile File="Generated.cs" Lines="$(TargetFramework)" Overwrite="true"/>'
    + '<ItemGroup><Compile Include="Generated.cs"/><GeneratedOnce Include="one"/></ItemGroup></Target>');
  const value = system(xml);
  const contexts = value.projects.get('App/App.csproj').contexts;
  for (const context of contexts) {
    const run = value.runTargets(context.path, undefined, {phase: 'beforeCompile', contextId: context.id});
    assert.equal(run.success, true, JSON.stringify(run.diagnostics));
  }
  for (const context of contexts) {
    assert.equal(value.buildFile('App/Generated.cs', {contextId: context.id}).text, context.targetFramework + '\n');
  }
  const first = contexts[0];
  const repeated = value.runTargets(first.path, undefined, {phase: 'beforeCompile', contextId: first.id});
  assert.equal(repeated.success, true, JSON.stringify(repeated.diagnostics));
  assert.equal(repeated.project.evaluatedItems.GeneratedOnce.length, 1);
  assert.equal(repeated.project.evaluatedItems.Compile.length, 1);
});

test('post-compile input hydration failure is atomic and retries retain the same pending build phase', () => {
  const value = system(sdk('', '<Target Name="CopyData" AfterTargets="AfterCompile">'
    + '<Copy SourceFiles="data.bin" DestinationFiles="copied.bin"/></Target>'),
  [{path: 'App/data.bin', lazy: true, size: 2}]);
  const prepared = value.runTargets('App/App.csproj', undefined, {phase: 'beforeCompile'});
  assert.equal(prepared.success, true);
  const output = value.buildPlan().units[0].output;
  const options = {phase: 'afterCompile', outputPath: output, outputs: [{path: output, bytes: Uint8Array.of(77, 90)}]};
  const first = value.runTargets('App/App.csproj', undefined, options);
  assert.equal(first.success, false);
  assert.deepEqual(first.requiredFiles, ['App/data.bin']);
  assert.equal(value.files.has(output.slice(1)), false);
  value.files.set('App/data.bin', {path: 'App/data.bin', bytes: Uint8Array.of(1, 2)});
  const second = value.runTargets('App/App.csproj', undefined, options);
  assert.equal(second.success, true, JSON.stringify(second.diagnostics));
  assert.deepEqual(value.files.get('App/copied.bin').bytes, Uint8Array.of(1, 2));
});

test('SDK compiler defaults preserve props replacement and apply configuration and compiler-time defaults', () => {
  const value = system(sdk('<DefineConstants>PROJECT</DefineConstants><DisableImplicitFrameworkDefines>true</DisableImplicitFrameworkDefines>'));
  assert.deepEqual(value.compilationOptions().defines, ['PROJECT', 'DEBUG']);
  assert.deepEqual(value.compilationOptions().noWarn, ['1701', '1702', '8002']);
  assert.deepEqual(value.compilationOptions().warningsAsErrors, ['NU1605', 'SYSLIB0011']);
  const disabled = system(sdk('<DisableImplicitConfigurationDefines>true</DisableImplicitConfigurationDefines>'
    + '<DisableImplicitFrameworkDefines>true</DisableImplicitFrameworkDefines><WarningsAsErrors>CS0168</WarningsAsErrors>'
    + '<EnableUnsafeBinaryFormatterSerialization>true</EnableUnsafeBinaryFormatterSerialization>'));
  assert.deepEqual(disabled.compilationOptions().defines, ['TRACE']);
  assert.deepEqual(disabled.compilationOptions().warningsAsErrors, ['CS0168']);
});

test('public metadata lookup prefers exact spelling and never resolves inherited object members', () => {
  const metadata = {Aliases: 'exact', aliases: 'lower'};
  assert.equal(getCaseInsensitive(metadata, 'Aliases'), 'exact');
  assert.equal(getCaseInsensitive(metadata, 'ALIASES'), 'exact');
  assert.equal(getCaseInsensitive(metadata, 'aliases'), 'lower');
  assert.equal(getCaseInsensitive(metadata, 'toString'), undefined);
  assert.equal(getCaseInsensitive(undefined, 'Aliases'), undefined);
});
