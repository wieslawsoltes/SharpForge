export function contributeDebuggerAutomation(automation,context){

return automation.contributeAutomation('',{loadPdb:(bytes,sources)=>context.advancedTools.loadPdb(bytes,sources),
setNextStatement:target=>context.advancedTools.setNext(target),
getThreads:()=>context.runtime.request('threads'),
getParallelStacks:()=>context.runtime.request('parallelStacks'),
selectThread:id=>context.advancedTools.selectThread(id),
freezeThread:(threadId,frozen)=>context.runtime.request('freezeThread',{threadId,frozen}),
beginHotReload:()=>context.advancedTools.beginEdit(),
cancelHotReload:()=>context.advancedTools.cancelEdit(),
applyHotReload:options=>context.advancedTools.applyChanges(options),
applyAssemblyChanges:bytes=>context.advancedTools.applyAssembly(bytes),
evaluateFunction:(expression,options)=>context.advancedTools.invoke(expression,options),
setUIRenderer:renderer=>{context.advancedTools.ensureApp();context.advancedTools.renderer=renderer;context.advancedTools.appHost.setBackend(renderer);},
getUIMetrics:()=>[...context.advancedTools.metrics.values()],
uiSettled:()=>context.advancedTools.appHost?.settled(),
getBreakpoints:()=>structuredClone(context.state.breakpoints),
toggleBreakpoint:context.toggleBreakpoint,
editBreakpoint:context.editBreakpoint,
setBreakpoints:async(uri,bps)=>{context.state.breakpoints[uri]=structuredClone(bps);await context.syncBreakpoints(uri);context.setEditorDecorations();context.renderPanel('breakpoints');},
debug:(options={})=>context.launch(true,options),
configureDebug:patch=>context.debugTools.configure(patch),
setFunctionBreakpoints:items=>context.debugTools.setFunctions(items),
immediate:expression=>context.debugTools.evaluateImmediate(expression),
step:context.step,
evaluate:expression=>context.runtime.request('evaluate',{expression,frameId:context.state.frameId})});
}
