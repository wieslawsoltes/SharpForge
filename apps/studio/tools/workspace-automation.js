export function contributeWorkspaceAutomation(automation,context){

return automation.contributeAutomation('',{getRuntimeInfo:()=>context.runtime.request('runtimeInfo'),
openProjectWizard:context.openProjectWizard,
openItemWizard:context.openItemWizard,
openWorkspaceZip:context.openWorkspaceZip,
exportWorkspaceZip:context.workspaceZipBytes,
saveWorkspaceFolder:context.saveWorkspaceFolder,
getWorkspace:()=>({records:context.explorerContext().records.map(r=>({...r,bytes:r.bytes?Array.from(r.bytes):undefined})),folders:[...context.state.folders],settings:context.workspaceSettings()}),
getTemplates:()=>({projects:context.projectTemplates,items:context.itemTemplates}),
getPdb:()=>context.state.pdb?.slice(),
getUIScene:()=>context.runtime.request('uiScene'),
advanceUIAnimations:milliseconds=>context.runtime.request('uiAnimationAdvance',{milliseconds}),
setUIAnimationMode:manual=>context.runtime.request('uiAnimationMode',{manual}),
dispatchUIEvent:(id,event,payload)=>context.runtime.request('uiEvent',{id,event,payload}),
setKeymap:context.setEditorKeymap,
getKeymap:()=>({id:context.state.keymap,mode:context.editor?.modalMode??'editing'}),
getExplorer:()=>({...context.solutionExplorer.snapshot(),busy:!!(context.explorerActions.busy||context.explorerActions.runningMutation)}),
explorerCommand:(id,path,kind)=>{const node=[...context.solutionExplorer.model.nodes.values()].find(n=>n.path===path&&(!kind||n.kind===kind))??context.solutionExplorer.model.roots[0];return context.explorerActions.run(id,node);},
version:'0.14.0',
getAssembly:()=>context.state.assembly?.slice(),
inspectAssembly:context.openAssemblyExplorer,
invokeAssembly:context.invokeAssembly,
breakOnWrite:context.breakOnWrite,
assembleIL:text=>context.compiler.request('assembleIL',{text}),
configureExtensions:async config=>{context.state.extensionConfig=config;await context.requestCompiler('configureExtensions',config);context.saveLocal();context.state.buildDirty=true;return context.build();},
getGeneratedSources:()=>context.state.result?.generatedSources??[],
importFiles:context.importFiles,
loadDiskRecords:context.loadDiskRecords,
setStartupProject:context.setStartupProject,
saveToDisk:context.saveToDisk,
applyRefactoring:context.applyRefactoring,
getEditorState:uri=>{const e=context.editors.get(uri);return e?{keymap:e.keymap,mode:e.modalMode,value:e.value,start:e.input.selectionStart,end:e.input.selectionEnd,undo:e.history.length,executionLine:e.executionLine,selectedFrameLine:e.selectedFrameLine,executionPoint:e.executionPoint,highlight:e.highlightMetrics}:null;},
getNavigation:()=>context.navigation.snapshot(),
openTool:context.setPanel,
importAssembly:context.importAssembly,
loadSample:context.loadSample,
build:context.build,
run:()=>context.launch(false),
selectDebugFrame:context.selectDebugFrame,
showNextStatement:context.showNextStatement,
getDebugSettings:()=>structuredClone(context.state.debugSettings),
execute:context.execute,
openFile:context.openFile});
}
