import { parseArgs } from 'node:util';
import { readFileSync, writeFileSync } from 'node:fs';
import { readJSON, isMain } from './lib/io.js';
export function codeowners(ownership, owner = '@wieslawsoltes') {
  if (!/^@[\w-]+(?:\/[\w-]+)?$/.test(owner)) throw new Error('Invalid CODEOWNERS owner');
  return '# Generated by scripts/planning/gen-codeowners.js. Do not edit.\n# Area team placeholders document routing until real GitHub teams exist.\n' + Object.entries(ownership.areas).sort().map(([area, value]) => `\n# ${area}; team placeholder: @ORG/area-${area.toLowerCase()}\n${[...value.write, ...value.evidence].map(path => `/${path} ${owner}`).join('\n')}`).join('\n') + '\n';
}
if (isMain(import.meta.url)) {
  const { values } = parseArgs({ options: { check: { type: 'boolean' }, output: { type: 'string', default: '.github/CODEOWNERS' } } });
  const expected = codeowners(readJSON('planning/contracts/ownership.json'));
  if (values.check) { if (readFileSync(values.output, 'utf8') !== expected) throw new Error('CODEOWNERS drift; regenerate'); } else writeFileSync(values.output, expected);
}
